import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";
import { PGlite } from "@electric-sql/pglite";
const a="10000000-0000-4000-8000-000000000001",b="10000000-0000-4000-8000-000000000002";
const wa="20000000-0000-4000-8000-000000000001",wb="20000000-0000-4000-8000-000000000002",unknown="20000000-0000-4000-8000-000000000003";
const pa="30000000-0000-4000-8000-000000000001",pb="30000000-0000-4000-8000-000000000002",sameOwner="30000000-0000-4000-8000-000000000003";
const upload="40000000-0000-4000-8000-000000000001";
test("ordered migrations enforce owned reads, atomic limits, parent consistency, private assets and confirmed email sync",async()=>{
  const db=new PGlite();
  try {
    await db.exec(`
      create role anon;create role authenticated;create role service_role bypassrls;
      create schema auth;create schema storage;
      create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      create function auth.jwt() returns jsonb language sql as $$ select '{}'::jsonb $$;
      grant usage on schema auth to authenticated;
      create table auth.users(id uuid primary key,email text,is_anonymous boolean default false);
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(id uuid,bucket_id text);
      create table workspaces(id uuid primary key,user_id uuid,name text not null,content_theme text not null,linked_accounts jsonb,narration_voice_id text,visual_aesthetic text,aspect_ratio text,video_language text,duration_pref text,created_at timestamptz default now());
      create table video_projects(id uuid primary key,workspace_id uuid references workspaces(id),topic text,status text default 'drafting');
      create table media(id uuid primary key,project_id uuid references video_projects(id),media_type text,source text,status text,storage_path text,url text,original_filename text);
      create table scenes(id uuid primary key,project_id uuid references video_projects(id),media_id uuid references media(id));
      create table timeline_items(id uuid primary key,project_id uuid references video_projects(id),media_id uuid references media(id));
      create table channel_facts(id uuid primary key,workspace_id uuid references workspaces(id));
      create policy old_all_workspaces on workspaces for all using(true) with check(true);
      insert into workspaces(id,user_id,name,content_theme) values('${wa}','${a}','A','theme'),('${wb}','${b}','B','theme'),('${unknown}',null,'Unknown','theme');
      insert into video_projects(id,workspace_id,topic) values('${pa}','${wa}','A project'),('${pb}','${wb}','B project'),('${sameOwner}','${wa}','Another A project');
    `);
    for(const file of ["001-auth-only-containment.sql","002-account-identities-and-leads.sql","003-confirmed-email-sync.sql","004-owned-records.sql","005-private-assets.sql","006-account-request-limits.sql","007-resumable-onboarding.sql"]) await db.exec(await readFile(new URL(`../../db/auth/${file}`,import.meta.url),"utf8"));
    await db.query("insert into auth.users(id,email) values($1,$2),($3,$4)",[a,"a@example.com",b,"b@example.com"]);
    await db.query("select set_config('request.jwt.claim.sub',$1,false)",[a]);
    await db.exec("set role authenticated");
    assert.deepEqual((await db.query("select id from workspaces")).rows,[{id:wa}]);
    assert.equal((await db.query("select count(*)::int n from video_projects")).rows[0].n,2);
    await assert.rejects(db.query("update workspaces set user_id=$1 where id=$2",[b,wa]),/permission denied/);
    const op="50000000-0000-4000-8000-000000000001",payload={name:"New A",content_theme:"Documentary"};
    assert.equal((await db.query("select create_owned_workspace($1,$2) id",[payload,op])).rows[0].id,op);
    assert.equal((await db.query("select create_owned_workspace($1,$2) id",[payload,op])).rows[0].id,op);
    await assert.rejects(db.query("select create_owned_workspace($1,$2)",[{...payload,visual_aesthetic:"changed"},op]),/OPERATION_REUSED/);
    await assert.rejects(db.query("select create_owned_workspace($1,$2)",[{...payload,user_id:b},"50000000-0000-4000-8000-000000000002"]),/INVALID_FIELDS/);
    await db.query("select create_owned_workspace($1,$2)",[payload,"50000000-0000-4000-8000-000000000003"]);
    await assert.rejects(db.query("select create_owned_workspace($1,$2)",[payload,"50000000-0000-4000-8000-000000000004"]),/TEST_WORKSPACE_LIMIT/);
    await assert.rejects(db.query("select rename_owned_resource('project',$1,'tamper')",[pb]),/RESOURCE_UNAVAILABLE/);
    await db.query("select rename_owned_resource('project',$1,'Updated owned topic')",[pa]);
    const hash="a".repeat(64);
    await assert.rejects(db.query("select reserve_private_media($1,$2,'image/png',20,$3,'image.png')",[upload,pb,hash]),/RESOURCE_UNAVAILABLE/);
    await db.query("select reserve_private_media($1,$2,'image/png',20,$3,'image.png')",[upload,pa,hash]);
    await db.query("select reserve_private_media($1,$2,'image/png',20,$3,'image.png')",[upload,pa,hash]);
    await assert.rejects(db.query("select reserve_private_media($1,$2,'image/png',21,$3,'image.png')",[upload,pa,hash]),/OPERATION_REUSED/);
    await assert.rejects(db.query("select finish_private_media($1,$2,$3,true)",[upload,a,hash]),/permission denied/);
    await db.exec("do $$ begin for i in 1..5 loop perform public.admit_account_request('import'); end loop; begin perform public.admit_account_request('import'); raise exception 'LIMIT_NOT_ENFORCED'; exception when others then if sqlerrm<>'REQUEST_RATE_LIMIT' then raise; end if; end; end $$");
    await db.exec("reset role;set role service_role");
    await db.query("select finish_private_media($1,$2,$3,true)",[upload,a,hash]);
    await db.query("select finish_private_media($1,$2,$3,false)",[upload,a,hash]);
    assert.equal((await db.query("select state from private_assets where id=$1",[upload])).rows[0].state,"ready");
    await db.exec("reset role");
    await assert.rejects(db.exec(await readFile(new URL("../../db/fix-media-rls.sql",import.meta.url),"utf8")),/SUPERSEDED_BY_ACCOUNT_ACCESS/);
    await assert.rejects(db.query("insert into scenes values($1,$2,$3)",[upload,sameOwner,upload]),/same_project/);
    await assert.rejects(db.query("insert into timeline_items values($1,$2,$3)",[upload,pb,upload]),/same_project/);
    await db.query("update auth.users set email='confirmed-new@example.com' where id=$1",[a]);
    assert.equal((await db.query("select email from users where id=$1",[a])).rows[0].email,"confirmed-new@example.com");
    await db.query("select set_config('request.jwt.claim.sub',$1,false)",[b]);await db.exec("set role authenticated");
    assert.equal((await db.query("select count(*)::int n from private_assets")).rows[0].n,0);
    assert.equal((await db.query("select count(*)::int n from media")).rows[0].n,0);
    await assert.rejects(db.query("select reserve_private_media($1,$2,'image/png',20,$3,'image.png')",[upload,pa,hash]),/RESOURCE_UNAVAILABLE/);
    // Phase 7: database-derived identity, resumable steps, stale-save protection and atomic draft creation.
    const settings={workspaceId:null,name:"B channel",content_theme:"History",visual_aesthetic:"Cinematic",aspect_ratio:"Vertical 9:16",video_language:"English",duration_pref:"60-90s",topic:""};
    const save=async(revision,value)=>(await db.query("select save_account_onboarding($1,$2) state",[revision,value])).rows[0].state;
    const finish=async(revision)=>(await db.query("select public.complete_account_onboarding($1::integer) state",[revision])).rows[0].state;
    assert.equal((await save(0,settings)).revision,1);
    assert.equal((await save(0,settings)).revision,1);
    await assert.rejects(save(0,{...settings,name:"Stale"}),/STALE_SETUP/);
    await assert.rejects(finish(1),/TOPIC_REQUIRED/);
    for(const invalid of [{...settings,workspaceId:wa},{...settings,visual_aesthetic:"AI"},{...settings,topic:null},{...settings,actor_id:a},{...settings,name:" "},{...settings,video_language:"unknown"}]) await assert.rejects(save(1,invalid),/RESOURCE_UNAVAILABLE|INVALID_SETUP/);
    const completeSettings={...settings,topic:"A manual draft"};
    await save(1,completeSettings);
    const done=await finish(2);
    assert.deepEqual(await finish(2),done);
    assert.deepEqual(await finish(1),done);
    assert.equal((await db.query("select count(*)::int n from video_projects where id=$1 and status='drafting'",[done.project_id])).rows[0].n,1);
    assert.equal((await db.query("select count(*)::int n from workspaces where user_id=$1",[b])).rows[0].n,2);
    await assert.rejects(save(2,completeSettings),/SETUP_COMPLETE/);
    await assert.rejects(db.query("update account_onboarding set project_id=$1",[pa]),/permission denied/);
    await db.exec("reset role"); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[a]); await db.exec("set role authenticated");
    assert.equal((await db.query("select count(*)::int n from account_onboarding")).rows[0].n,0);
    assert.equal((await db.query("select count(*)::int n from video_projects where id=$1",[done.project_id])).rows[0].n,0);
    await assert.rejects(finish(2),/SETUP_REQUIRED/);
    await save(0,completeSettings);
    await assert.rejects(finish(1),/TEST_WORKSPACE_LIMIT/);
    assert.equal((await db.query("select project_id from account_onboarding")).rows[0].project_id,null);
    await save(1,{...completeSettings,workspaceId:wa});
    const reused=await finish(2);
    assert.equal(reused.workspace_id,wa);
    assert.equal((await db.query("select count(*)::int n from workspaces")).rows[0].n,3);
    // No scenes, media, scripts, jobs, credits or provider work is created by completion.
    assert.equal((await db.query("select count(*)::int n from scenes where project_id=$1",[reused.project_id])).rows[0].n,0);
    assert.equal((await db.query("select count(*)::int n from media where project_id=$1",[reused.project_id])).rows[0].n,0);
    await db.exec("reset role;set role anon");await assert.rejects(db.query("select * from public.workspaces"),/permission denied/);
    await assert.rejects(db.query("select * from public.account_onboarding"),/permission denied/);
    await assert.rejects(finish(2),/permission denied/);
    await db.exec("reset role");
    assert.equal((await db.query("select count(*)::int n from workspaces where user_id is null")).rows[0].n,1);
    await assert.rejects(db.query("insert into workspaces(id,name,content_theme) values($1,'No owner','theme')",["60000000-0000-4000-8000-000000000001"]),/account_owner_required/);
  }finally{await db.close();}
});
